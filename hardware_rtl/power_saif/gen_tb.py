#!/usr/bin/env python3
"""Generate per-design array-level power testbenches + DC power tcl for the
SAIF-annotated power flow. Every primary-input bus is driven with fresh
uniform-random bits each cycle (high-activity, uncorrelated-data operating
point), acc_shift pulses every 32 cycles to exercise the shift-out mux, and a
backward-SAIF is dumped over a steady-state window. Each input port X_in has a
matching output port X_out of equal width (systolic pass-through + accumulator),
so outputs are derived by name."""
