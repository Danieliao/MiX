# SITE CONFIGURATION: directory holding the .db timing library, and the .db file
# name -- the same two values you set in syn/<Design>/syn.tcl.
# Paper used TSMC 28nm tcbn28hpcplusbwp30p140ssg0p81v125c.db.
LIB = "<PATH-TO-DIRECTORY-CONTAINING-THE-.db-TIMING-LIBRARY>"
TARGET_DB = "<STANDARD-CELL-TIMING-LIBRARY>.db"
OPCOND = "<OPERATING-CONDITION-NAME>"

def fill_lines(port, w, indent="        "):
    """Emit SV lines to slam random bits onto a port of width w."""
    out = []
    nch = w // 32
    rem = w % 32
    if nch > 0:
        out.append(f"{indent}for (int k = 0; k < {nch}; k++) {port}[k*32 +: 32] = $random;")
    if rem > 0:
        out.append(f"{indent}{port}[{nch*32} +: {rem}] = $random;")
    return out

def gen_tb(design, top, ports):
    sigs, conns, drive = [], ["        .clk(clk), .rst_n(rst_n), .acc_shift(acc_shift)"], []
    for name, w in ports:
        oname = name[:-3] + "_out"
        sigs.append(f"    logic [{w-1}:0] {name};")
        sigs.append(f"    logic [{w-1}:0] {oname};")
        conns.append(f"        .{name}({name}), .{oname}({oname})")
        drive += fill_lines(name, w)
    sig_blk = "\n".join(sigs)
    conn_blk = ",\n".join(conns)
    drive_blk = "\n".join(drive)
    return f"""// AUTO-GENERATED by gen_tb.py -- array-level power-activity testbench for the
// synthesized {top} netlist. Every primary-input bus gets fresh uniform-random
// bits each cycle (high-activity, uncorrelated data); a backward-SAIF is dumped
// over a steady-state window for SAIF-annotated power. Functional correctness is
// irrelevant -- only representative switching activity.
`timescale 1ns/10ps

module tb;
    localparam int WARMUP  = {WARMUP};
    localparam int CAPTURE = {CAPTURE};
    localparam int SHIFT_PERIOD = {SHIFT_PERIOD};

    logic clk = 1'b0;
    logic rst_n;
    logic acc_shift;

{sig_blk}

    {top} dut (
{conn_blk}
    );

    // 2 ns clock (matches 500 MHz synthesis target)
    always #1 clk = ~clk;

    task automatic drive_random;
{drive_blk}
    endtask

    initial begin
        rst_n = 1'b0; acc_shift = 1'b0;
        repeat (4) @(posedge clk);
        rst_n = 1'b1;

        for (int c = 0; c < WARMUP; c++) begin
            @(negedge clk);
            drive_random();
            acc_shift = (c % SHIFT_PERIOD == SHIFT_PERIOD-1);
        end

        $set_toggle_region(tb.dut);
        $toggle_start;
        for (int c = 0; c < CAPTURE; c++) begin
            @(negedge clk);
            drive_random();
            acc_shift = (c % SHIFT_PERIOD == SHIFT_PERIOD-1);
        end
        $toggle_stop;
        $toggle_report("{top}.saif", 1.0e-9, "tb.dut");

        $display("[tb] {design} SAIF capture complete: %0d cycles", CAPTURE);
        $finish;
    end
endmodule
"""

def gen_tcl(design, top, syn):  # noqa
    return f"""# AUTO-GENERATED -- SAIF-annotated power for {design} ({top}).
# Re-powers the already-synthesized .ddc; only switching activity differs.
set top "{top}"
set search_path [list "." "{LIB}"]
set target_library [list "{TARGET_DB}"]
set_app_var target_library [concat $target_library]
set_app_var link_library [concat "*" $target_library]
set LIB_NAME [file rootname "{TARGET_DB}"]

# Requires syn/{syn} to have been run first (it writes the .ddc reused here).
read_file -format ddc "../../syn/{syn}/output/${{top}}.ddc"
current_design $top
link

set_operating_conditions "{OPCOND}" -library $LIB_NAME
create_clock -name clk -period 2 [get_ports clk]

reset_switching_activity
read_saif -input "${{top}}.saif" -instance_name "tb/dut"

report_saif -hier > saif_coverage.rpt
report_power -hier -analysis_effort medium -nosplit > power_saif.rpt
quit
"""

def main():
    base = os.path.dirname(os.path.abspath(__file__))
    for design, (top, syn, ports) in DESIGNS.items():
        d = os.path.join(base, design)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, f"{design.lower()}_power_tb.sv"), "w") as f:
            f.write(gen_tb(design, top, ports))
        with open(os.path.join(d, "power_saif.tcl"), "w") as f:
            f.write(gen_tcl(design, top, syn))
        print(f"{design:18s} top={top:34s} syn=syn/{syn}")

if __name__ == "__main__":
    main()
